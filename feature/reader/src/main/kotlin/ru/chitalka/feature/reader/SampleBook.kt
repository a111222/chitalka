            "вперёд, на другой берег, где начинался чужой сад.",
    )

    val chapter = Chapter(
        index = 0,
        title = TITLE,
        blocks = listOf(Block.Heading(TITLE, 1)) + paragraphs.map { Block.Paragraph(it) },
    )
