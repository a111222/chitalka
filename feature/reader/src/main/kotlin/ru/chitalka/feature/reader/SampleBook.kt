    const val TITLE = "Сад за рекой"
    const val AUTHOR = "Демонстрационный текст"

    val content = BookContent(
        title = TITLE,
        author = AUTHOR,
        language = "ru",
        chapterCount = 1,
        toc = listOf(TocEntry("Сад за рекой", level = 0, chapterIndex = 0)),
    )

    private val paragraphs = listOf(
        "Утро начиналось с запаха бумаги. Мать раскрывала окна в сад, и ветер с реки " +
            "перелистывал оставленную на подоконнике книгу, будто тоже хотел узнать, чем всё кончится.",
        "Сад спускался к воде тремя уступами. На верхнем росли яблони, такие старые, что их ветви " +
            "приходилось подпирать рогатинами, на среднем — смородина и крыжовник, а нижний, у самой реки, " +
            "никто толком не возделывал: там жили крапива, мята и лодка, перевёрнутая кверху дном.",
        "Лодку когда-то просмолил дед. Он же вырезал на её носу маленькую птицу, которую все в доме " +
            "называли зимородком, хотя на зимородка она не походила ничуть.",
        "— Птица должна смотреть вперёд, — говорил дед, — а куда плыть, решает тот, кто на вёслах.",
        "Он умер весной, когда яблони только начали цвести, и лодку с тех пор не спускали на воду.",
        "Летом в дом приезжали гости. Они привозили новости из города, коробки конфет и непременно " +
            "книги: толстые романы в выцветших переплётах, тонкие сборники стихов, путеводители по странам, " +
            "в которых никто из них не бывал.",
        "Книги оставались в доме навсегда. Их ставили в резной шкаф в гостиной, и к концу каждого лета " +
            "полки прогибались чуть сильнее, а отец обещал, что осенью непременно сделает ещё одну.",
        "Вечерами в гостиной зажигали лампу под зелёным абажуром. Свет падал на корешки, и золотые буквы " +
