            "ли тебе эта книга и поймёшь ли ты в ней хоть что-нибудь. Считалось, что книга сама знает, " +
            "когда ей быть прочитанной.",
        "В то лето я выбрал книгу без названия. Переплёт у неё был тёмно-синий, гладкий, без единой буквы, " +
            "а внутри, на первой странице, кто-то вывел карандашом: «Для того, кто дочитает».",
